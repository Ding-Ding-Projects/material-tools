import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UPSTREAM_REPOSITORY = 'ChrisTitusTech/winutil';
const UPSTREAM_REF = 'ea5de27b6c66fe4f4a4c6513887d0fe5a1cd8bff';
const UPSTREAM_PATH = 'config/applications.json';
const EXPECTED_COUNT = 227;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src', 'shared', 'application-catalog.generated.ts');

function requireText(value, field, key, maxLength = 2_000) {
  if (typeof value !== 'string' || value.length === 0 || value.length > maxLength) {
    throw new Error(`${key}.${field} must be a non-empty string no longer than ${maxLength} characters.`);
  }
  return value;
}

function packageIds(value, field, key) {
  if (value === undefined || value === null || value === '' || value === 'na') return [];
  const text = requireText(value, field, key, 400);
  const ids = text.split(';');
  if (ids.length > 4) throw new Error(`${key}.${field} declares too many package identifiers.`);
  for (const id of ids) {
    if (!/^[A-Za-z0-9][A-Za-z0-9.+_:\-]*$/.test(id)) {
      throw new Error(`${key}.${field} contains an unsupported package identifier.`);
    }
  }
  return ids;
}

const endpoint = `repos/${UPSTREAM_REPOSITORY}/contents/${UPSTREAM_PATH}?ref=${UPSTREAM_REF}`;
const raw = execFileSync('gh', ['api', '-H', 'Accept: application/vnd.github.raw+json', endpoint], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 4 * 1024 * 1024,
});
const parsed = JSON.parse(raw);
if (!parsed || Array.isArray(parsed) || typeof parsed !== 'object') {
  throw new Error('The upstream application catalog is not a JSON object.');
}

const catalog = Object.entries(parsed).map(([key, value]) => {
  if (!/^[A-Za-z0-9][A-Za-z0-9._\-]*$/.test(key)) throw new Error(`Unsupported catalog key: ${key}`);
  if (!value || Array.isArray(value) || typeof value !== 'object') throw new Error(`${key} must be an object.`);
  const link = requireText(value.link, 'link', key, 500);
  if (!link.startsWith('https://')) throw new Error(`${key}.link must use HTTPS.`);
  const winget = packageIds(value.winget, 'winget', key);
  const choco = packageIds(value.choco, 'choco', key);
  if (winget.length === 0 && choco.length === 0) throw new Error(`${key} must expose at least one supported package identifier.`);
  return {
    key,
    name: requireText(value.content, 'content', key, 120),
    description: requireText(value.description, 'description', key),
    category: requireText(value.category, 'category', key, 80),
    winget,
    choco,
    link,
    foss: value.foss === true,
  };
}).sort((left, right) => left.name.localeCompare(right.name, 'en', { sensitivity: 'base' }));

if (catalog.length !== EXPECTED_COUNT) {
  throw new Error(`Expected ${EXPECTED_COUNT} applications at ${UPSTREAM_REF}, received ${catalog.length}.`);
}

const digest = createHash('sha256').update(raw).digest('hex');
const source = `// Generated by scripts/import-winutil-applications.mjs from the pinned MIT-licensed upstream catalog.\n`
  + `// Do not edit this file by hand.\n\n`
  + `export const APPLICATION_CATALOG_UPSTREAM = {\n`
  + `  repository: ${JSON.stringify(UPSTREAM_REPOSITORY)},\n`
  + `  ref: ${JSON.stringify(UPSTREAM_REF)},\n`
  + `  path: ${JSON.stringify(UPSTREAM_PATH)},\n`
  + `  sha256: ${JSON.stringify(digest)},\n`
  + `} as const;\n\n`
  + `export interface ApplicationCatalogItem {\n`
  + `  key: string;\n`
  + `  name: string;\n`
  + `  description: string;\n`
  + `  category: string;\n`
  + `  winget: readonly string[];\n`
  + `  choco: readonly string[];\n`
  + `  link: string;\n`
  + `  foss: boolean;\n`
  + `}\n\n`
  + `export const APPLICATION_CATALOG = ${JSON.stringify(catalog, null, 2)} as const satisfies readonly ApplicationCatalogItem[];\n`;

writeFileSync(outputPath, source, 'utf8');
console.log(`Wrote ${catalog.length} applications to ${path.relative(root, outputPath)}.`);
console.log(`Pinned source SHA-256: ${digest}`);
